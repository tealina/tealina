import fs from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vite-plus/test'
import { templateRootDir } from '../src/core.js'

/**
 * T7 — the opt-in merge playbook, held to the facts it tells an agent to rely on.
 *
 * `--integrate` copies `template/integration/INTEGRATION.md` into the project root. The
 * file is prose, so the risk is not a missing import: it is a playbook that quietly stops
 * matching the template — a package path that moved, a generated artifact that was renamed,
 * an `--integrate` spelled differently in the README. An agent following it would then
 * either fail or, worse, succeed against the wrong names.
 *
 * These assertions are deliberately a handful of load-bearing anchors rather than the
 * document's text: the prose is free to change, the names it points at are not.
 */

const rel = 'integration/INTEGRATION.md'
const doc = fs.readFileSync(path.join(templateRootDir, rel), 'utf-8')

const contains = (needle: string) => {
  expect(doc, `the integration playbook must mention \`${needle}\``).toContain(
    needle,
  )
}

describe('integration playbook', () => {
  it('ships with the scaffold', () => {
    expect(fs.existsSync(path.join(templateRootDir, rel))).toBe(true)
  })

  it('is the only file in its template directory', () => {
    // `create` names this one file. Anything else placed beside it would not be copied,
    // and the manifest test's walk does not cover this directory, so this is the line
    // that notices.
    expect(fs.readdirSync(path.join(templateRootDir, 'integration'))).toEqual([
      'INTEGRATION.md',
    ])
  })

  it('covers both integration shapes', () => {
    contains('Shape A: mount into an existing server')
    contains('Shape B: merge the whole backend')
    // The two packages Shape A needs, and the one it deliberately leaves behind.
    contains('backend/core')
    contains('backend/api-v1')
    contains('backend/server')
  })

  it('names the flag that writes it', () => {
    contains('create-tealina --integrate')
  })

  it('names the generated artifacts and the commands that own them', () => {
    for (const artifact of [
      'types/api.d.ts',
      'docs/api.json',
      'exports["./api"]',
      'ApiTypesForDoc',
      '__@ResponseFlagSymbol',
    ]) {
      contains(artifact)
    }
    contains('align --check')
    contains('gdoc --check')
    // The one generated-file rule the other agent instructions state.
    contains('@generated by tealina')
  })

  it('lists the generated-project paths an agent will copy', () => {
    // The playbook speaks in the scaffold's own paths. If a package is ever moved, this
    // is the line that says the prose needs the same edit.
    for (const pkg of ['core', 'api-v1', 'server'] as const) {
      expect(
        fs.existsSync(path.join(templateRootDir, `${pkg}/express/src`)),
        `the playbook names backend/${pkg}, which the template no longer ships`,
      ).toBe(true)
    }
  })
})
