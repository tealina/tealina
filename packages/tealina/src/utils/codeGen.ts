import { relative } from 'pathe'
import type { DirInfo } from './withTypeFile'

const toRoutePath = (xs: string[]) => {
  const route = xs.map(v => v.replace(/\[/, ':').replace(/\]/, '')).join('/')
  return route
}

const IdentifierPattern = /^[A-Za-z_$][A-Za-z0-9_$]*$/

/**
 * A key is written bare when it is a plain identifier and quoted otherwise — `health`, but
 * `user/create` and `user/:id`. This is the same judgement a formatter makes when it walks
 * the file afterwards, so a generated barrel is already in the shape one would leave it in:
 * formatting the tree produces no diff, and `align` does not rewrite what a formatter wrote.
 */
const toPropKey = (key: string) =>
  IdentifierPattern.test(key) ? key : `'${key}'`

export const genTopIndexProp =
  (suffix = '') =>
  (dir: string) =>
    `  ${toPropKey(dir)}: import('./${dir}/index${suffix}'),`

export const genIndexProp =
  (suffix = '') =>
  (fullPathArr: string[]) => {
    const key = toRoutePath(fullPathArr)
    return `  ${toPropKey(key)}: import('./${fullPathArr.join('/')}${suffix}'),`
  }

/**
 * Written into every generated file so that a person (or an agent) who opens one knows not
 * to edit it. `align` compares this header along with the rest of the file, so a file
 * written before the header existed is rewritten once and then left alone.
 */
export const kGeneratedHeader = [
  '// @generated by tealina — do not edit.',
  '// Rebuild it with: tealina <api-dir> -a',
  '',
  '',
].join('\n')

export const genWithWrapper = (contens: string[]) =>
  [kGeneratedHeader + 'export default {', ...contens.sort(), '}', ''].join('\n')

/**
 * The fallback `types/<api-dir>.d.ts`, written when `align` cannot find one. It has to
 * export the same two names the template does — `gdoc` reads the first export by position,
 * and the frontend imports `ApiTypesForClient` through `exports["./api/v1"].types`.
 */
export const genTypeCode = (
  { apiDir, typesDir }: Omit<DirInfo, 'testDir'>,
  suffix: string,
) => {
  const relativeDotStr = relative(typesDir, apiDir)
  return [
    kGeneratedHeader + `import apis from '${relativeDotStr}/index${suffix}'`,
    `import type {`,
    `  ResolveApiTypeForClient,`,
    `  ResolveApiTypeForDoc,`,
    `} from './handler${suffix}'`,
    '',
    'type RawApis = typeof apis',
    '',
    'export type ApiTypesForDoc = {',
    "  [Method in keyof RawApis]: ResolveApiTypeForDoc<Awaited<RawApis[Method]>['default']>",
    '}',
    '',
    'export type ApiTypesForClient = {',
    "  [Method in keyof RawApis]: ResolveApiTypeForClient<Awaited<RawApis[Method]>['default']>",
    '}',
    '',
  ].join('\n')
}
